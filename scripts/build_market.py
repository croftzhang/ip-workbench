"""Build the illustrative market data:

    config/market.yaml        today's close: Treasury curve, mortgage rates, MBS coupon stack
    config/market_prev.yaml   prior close
    data/marks.csv            position-level prices for both closes

What is real and what is not
----------------------------
* Treasury par yields and the 30-year mortgage rate are rounded from public
  levels in early November 2026 (10-year about 4.88%, mortgage rate 7.18%).
  The 15-year mortgage rate and the intermediate curve points are filled in
  by hand to give a smooth curve.
* MBS prices are NOT observed prices. Each position's mark is this engine's
  model price at an assumed zero-volatility spread for its coupon
  (TARGET_ZV_BP), rounded to 1/32. Spreads rise with coupon because a static
  spread has to absorb the cost of the prepayment option. The coupon stack in
  the YAML files is the face-weighted average of those marks.
* The prior close is constructed (yields a few bp lower, spreads 2bp tighter)
  so that the day-over-day explain has something to explain.

To run on real data, replace the three files with real closes and marks;
nothing else depends on this script.

Usage:  python scripts/build_market.py
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from ipw.core import config as cfg
from ipw.core.curve import Curve
from ipw.core.engine import Engine
from ipw.core.pricing import present_value

ROOT = Path(__file__).resolve().parents[1]
TENORS = [0.5, 1, 2, 3, 5, 7, 10, 20, 30]

TODAY = {
    "as_of": date(2026, 11, 9),
    "yields": [4.26, 4.33, 4.56, 4.61, 4.69, 4.79, 4.88, 5.30, 5.26],
    "rate_30y": 7.18,
    "rate_15y": 6.50,
    "zv_shift_bp": 0.0,
}
PRIOR = {
    "as_of": date(2026, 11, 6),
    "yields": [4.25, 4.30, 4.50, 4.54, 4.61, 4.71, 4.81, 5.25, 5.22],
    "rate_30y": 7.14,
    "rate_15y": 6.46,
    "zv_shift_bp": -2.0,  # spreads were 2bp tighter at the prior close
}
TARGET_ZV_BP = {
    "MBS_30Y": {2.0: 50, 2.5: 52, 3.0: 54, 3.5: 57, 4.0: 62, 4.5: 70, 5.5: 95, 6.0: 116, 6.5: 140},
    "MBS_15Y": {1.5: 40, 2.0: 41, 2.5: 42, 4.5: 55, 5.5: 80},
}

TEMPLATE = """\
# {title}
#
# ILLUSTRATIVE DATA. Treasury yields and the 30-year mortgage rate are rounded
# from public early-November-2026 levels. MBS prices are model prices at an
# assumed spread stack, not observed quotes. Generated by scripts/build_market.py;
# replace this file with a real close to run on real data.

as_of: {as_of}

par_curve:                 # Treasury par yields, semi-annual bond-equivalent
  tenors_years: {tenors}
  yields_pct:   {yields}

mortgage_rates_pct:        # primary rates offered to borrowers
  rate_30y: {rate_30y:.2f}
  rate_15y: {rate_15y:.2f}

# Clean price per 100 face by sector and coupon. Positions are valued at their
# own marks in data/marks.csv; this stack prices anything without a mark, such
# as a hypothetical purchase in a what-if.
mbs_prices:
{prices}
"""


def round_32nds(price):
    return np.round(np.asarray(price) * 32) / 32


def model_marks(spec: dict, securities: pd.DataFrame, swaps: pd.DataFrame, model) -> pd.DataFrame:
    """Model price of every MBS position at its coupon's target spread, rounded to 1/32."""
    market = cfg.Market(
        spec["as_of"], Curve.from_quotes(TENORS, spec["yields"]), spec["rate_30y"], spec["rate_15y"]
    )
    engine = Engine(securities, swaps, market, model)
    env = engine.environment()
    cash, _ = engine.project(env)
    target = np.array(
        [
            TARGET_ZV_BP.get(a, {}).get(float(c), np.nan)
            for a, c in zip(securities["asset_type"], securities["coupon"])
        ]
    )
    spread = (np.nan_to_num(target) + spec["zv_shift_bp"]) / 1e4
    price = present_value(cash.total, env.curve.df, spread) / securities["current_face_mm"].to_numpy() * 100.0
    marks = securities[["position_id", "asset_type", "coupon", "current_face_mm"]].assign(
        as_of=spec["as_of"].isoformat(), price=round_32nds(price)
    )
    return marks[~np.isnan(target)]


def coupon_stack(marks: pd.DataFrame) -> dict[str, dict[float, float]]:
    stack: dict[str, dict[float, float]] = {}
    for (sector, coupon), grp in marks.groupby(["asset_type", "coupon"]):
        average = np.average(grp["price"], weights=grp["current_face_mm"])
        stack.setdefault(sector, {})[float(coupon)] = float(round_32nds(average))
    return stack


def write_yaml(path: Path, title: str, spec: dict, stack: dict) -> None:
    lines = []
    for sector, prices in stack.items():
        lines.append(f"  {sector}:")
        lines += [f"    {coupon:.1f}: {price:.5f}" for coupon, price in sorted(prices.items())]
    text = TEMPLATE.format(
        title=title, as_of=spec["as_of"].isoformat(), tenors=TENORS,
        yields="[" + ", ".join(f"{y:.2f}" for y in spec["yields"]) + "]",
        rate_30y=spec["rate_30y"], rate_15y=spec["rate_15y"], prices="\n".join(lines),
    )  # fmt: skip
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    securities = cfg.load_securities(ROOT / "data" / "portfolio.csv")
    swaps = cfg.load_swaps(ROOT / "data" / "hedges.csv")
    model = cfg.load_model(ROOT / "config" / "model.yaml")
    all_marks = []
    for name, title, spec in (
        ("market_prev.yaml", "Prior market close, used by the day-over-day explain", PRIOR),
        ("market.yaml", "Market close used for valuation", TODAY),
    ):
        marks = model_marks(spec, securities, swaps, model)
        write_yaml(ROOT / "config" / name, title, spec, coupon_stack(marks))
        all_marks.append(marks[["as_of", "position_id", "price"]])
    path = ROOT / "data" / "marks.csv"
    pd.concat(all_marks).to_csv(path, index=False, float_format="%.5f")
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
